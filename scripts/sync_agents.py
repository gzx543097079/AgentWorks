#!/usr/bin/env python3
"""Generate portable roles and host adapters from one team definition."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "Generated by scripts/sync_agents.py"


def generated(root=ROOT):
    team = json.loads((root / "config/team.json").read_text(encoding="utf-8"))
    for role in team["roles"]:
        instructions = "\n".join([
            team["standard"], *team["shared_instructions"],
            "角色：" + role["name"],
            "专长：" + "、".join(role["expertise"]), role["instructions"],
            "交付：" + "、".join(role["deliverables"]),
            "收到独立任务后只做本角色工作，不再委派。职责模式：" + role["mode"] + "。实际工具权限由宿主环境控制。",
            "优先遵守分配的任务包和项目输入；按 config/result.schema.json 交付，不依赖平台私有聊天记忆。"
        ])
        note = MARKER + "; edit config/team.json."
        yield "roles/" + role["id"] + ".md", "<!-- " + note + " -->\n# " + role["name"] + "\n\n" + instructions + "\n"
        fields = {"name": role["id"], "description": role["description"], "developer_instructions": instructions}
        yield ".codex/agents/" + role["id"] + ".toml", "# " + note + "\n" + "\n".join(
            key + " = " + json.dumps(value, ensure_ascii=False) for key, value in fields.items()
        ) + "\n"
        name = "agentworks-" + role["id"].replace("_", "-")
        frontmatter = "\n".join(key + ": " + json.dumps(value, ensure_ascii=False) for key, value in {
            "name": name, "description": role["description"], "model": "inherit"
        }.items())
        yield ".claude/agents/" + name + ".md", "---\n" + frontmatter + "\n---\n\n<!-- " + note + " -->\n" + instructions + "\n"
    source = root / ".agents/skills/agentworks/SKILL.md"
    yield ".claude/skills/agentworks/SKILL.md", source.read_text(encoding="utf-8")


def synchronize(root=ROOT, check=False):
    expected = dict(generated(root))
    changed = []
    for name, content in expected.items():
        path = root / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            changed.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    # Remove only our obsolete generated roles, never user-authored adapters.
    for folder in ("roles", ".codex/agents", ".claude/agents"):
        for path in (root / folder).glob("*"):
            if path.is_file() and path.suffix in (".md", ".toml") and str(path.relative_to(root)) not in expected:
                if MARKER in path.read_text(encoding="utf-8"):
                    changed.append(str(path.relative_to(root)) + "（已移除角色）")
                    if not check:
                        path.unlink()
    return changed


def main():
    check = "--check" in sys.argv
    changed = synchronize(check=check)
    print("通用、Codex、Claude 角色和技能配置一致" if not changed else ("需要同步：" if check else "已同步：") + ", ".join(changed))
    return int(check and bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
