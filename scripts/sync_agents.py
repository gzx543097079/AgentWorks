#!/usr/bin/env python3
"""Generate discoverable Codex roles from the portable team definition."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated():
    team = json.loads((ROOT / "config/team.json").read_text())
    for role in team["roles"]:
        instructions = "\n".join([
            team["standard"], *team["shared_instructions"],
            "角色：" + role["name"],
            "专长：" + "、".join(role["expertise"]),
            role["instructions"],
            "交付：" + "、".join(role["deliverables"]),
            "收到独立任务后只做本角色工作，不再委派。模式建议：" + role["mode"] + "。实际权限继承当前会话。"
        ])
        fields = {"name": role["id"], "description": role["description"], "developer_instructions": instructions}
        yield role["id"] + ".toml", "# Generated by scripts/sync_agents.py; edit config/team.json.\n" + "\n".join(
            key + " = " + json.dumps(value, ensure_ascii=False) for key, value in fields.items()
        ) + "\n"


def main():
    target = ROOT / ".codex/agents"
    check = "--check" in sys.argv
    if not check:
        target.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, content in generated():
        path = target / name
        if not path.exists() or path.read_text() != content:
            changed.append(name)
            if not check:
                path.write_text(content)
    print("角色配置一致" if not changed else ("需要同步：" if check else "已生成：") + ", ".join(changed))
    return int(check and bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
