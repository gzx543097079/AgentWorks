#!/usr/bin/env python3
"""Generate host adapters and mirror skill resources from their canonical source."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from agentworks.skills import role_skills

MARKER = "Generated by scripts/sync_agents.py"
MANIFEST = ".claude/skills/.agentworks-generated.json"


def generated(root=ROOT):
    team = json.loads((root / "config/team.json").read_text(encoding="utf-8"))
    for role in team["roles"]:
        skills = role_skills(root, role)
        instructions = "\n".join([
            team["standard"], *team["shared_instructions"],
            "角色：" + role["name"],
            "专长：" + "、".join(role["expertise"]), role["instructions"],
            "交付：" + "、".join(role["deliverables"]),
            "职责技能：" + "、".join(".agents/skills/" + item["name"] + "/SKILL.md" for item in skills),
            "开始前读取分配技能，仅按当前平台和任务加载其支持资料。任务包给出绝对路径时优先使用；技能资源允许在产品工作区外只读访问。",
            "收到独立任务后只做本角色工作，不再委派。职责模式：" + role["mode"] + "。实际工具权限由宿主环境控制。",
            "优先遵守分配的任务包和项目输入；按 config/result.schema.json 交付，不依赖平台私有聊天记忆。"
        ])
        note = MARKER + "; edit config/team.json and .agents/skills/."
        yield "roles/" + role["id"] + ".md", ("<!-- " + note + " -->\n# " + role["name"] + "\n\n" + instructions + "\n").encode()
        fields = {"name": role["id"], "description": role["description"], "developer_instructions": instructions}
        yield ".codex/agents/" + role["id"] + ".toml", ("# " + note + "\n" + "\n".join(
            key + " = " + json.dumps(value, ensure_ascii=False) for key, value in fields.items()
        ) + "\n").encode()
        name = "agentworks-" + role["id"].replace("_", "-")
        frontmatter = "\n".join(key + ": " + json.dumps(value, ensure_ascii=False) for key, value in {
            "name": name, "description": role["description"], "model": "inherit"
        }.items())
        yield ".claude/agents/" + name + ".md", ("---\n" + frontmatter + "\n---\n\n<!-- " + note + " -->\n" + instructions.replace(".agents/skills/", ".claude/skills/") + "\n").encode()
    for folder in sorted((root / ".agents/skills").glob("agentworks*")):
        if not folder.is_dir() or not (folder / "SKILL.md").is_file():
            continue
        role_skills(root, {"skills": [folder.name]})
        for path in sorted(folder.rglob("*")):
            if "__pycache__" in path.parts or path.suffix == ".pyc":
                continue
            if path.is_file():
                yield ".claude/skills/" + path.relative_to(root / ".agents/skills").as_posix(), path.read_bytes()


def safe_target(root, name):
    path = root / name
    if path.is_symlink() or any(p.is_symlink() for p in path.parents if p != root and root in p.parents):
        raise ValueError("同步目标不能为符号链接：" + name)
    if path.exists() and not path.is_file():
        raise ValueError("同步目标不是普通文件：" + name)
    return path


def synchronize(root=ROOT, check=False):
    root = Path(root).resolve()
    expected = dict(generated(root))
    skills = {name: content for name, content in expected.items() if name.startswith(".claude/skills/")}
    manifest = safe_target(root, MANIFEST)
    previous = json.loads(manifest.read_text()) if manifest.exists() else []
    if not isinstance(previous, list) or any(not isinstance(n, str) or not n.startswith(".claude/skills/agentworks") or ".." in Path(n).parts for n in previous):
        raise ValueError("技能同步清单无效。")
    # The old release only generated this one skill file. Other unowned collisions
    # must be resolved before any writes, rather than silently replacing user files.
    owned = set(previous) | {".claude/skills/agentworks/SKILL.md"}
    for name, content in expected.items():
        path = safe_target(root, name)
        if name in skills and name not in owned and path.exists() and path.read_bytes() != content:
            raise ValueError("保留未受同步管理的同名技能文件：" + name)
    retired = []
    for name in sorted(set(previous) - set(skills)):
        path = safe_target(root, name)
        if path.exists():
            retired.append(path)
    expected[MANIFEST] = (json.dumps(sorted(skills), ensure_ascii=False, indent=2) + "\n").encode()
    changed = []
    for name, content in expected.items():
        path = safe_target(root, name)
        if not path.exists() or path.read_bytes() != content:
            changed.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content)
    # Legacy generated role naming; preserve unrelated adapters, including files
    # with different naming conventions that this generator never owned.
    for folder in ("roles", ".codex/agents", ".claude/agents"):
        for path in (root / folder).glob("*"):
            if path.is_symlink() or not path.is_file() or path.suffix not in (".md", ".toml"):
                continue
            if folder == ".codex/agents" and path.stem.startswith("agentworks-"):
                continue
            if str(path.relative_to(root)) not in expected and MARKER in path.read_text(encoding="utf-8"):
                retired.append(path)
    for path in retired:
        changed.append(str(path.relative_to(root)) + "（已移除的生成文件）")
        if not check:
            path.unlink()
    return changed


def main():
    check = "--check" in sys.argv
    changed = synchronize(check=check)
    print("通用、Codex、Claude 角色和技能配置一致" if not changed else ("需要同步：" if check else "已同步：") + str(len(changed)) + " 个文件")
    return int(check and bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
